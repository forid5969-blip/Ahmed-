export function generateCandlesForSymbol(symbol: string, count = 48, basePrice = 25000): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice;
  const now = Date.now();
  const interval = 15 * 60 * 1000; // 15 mins

  // Deterministic seed by symbol
  let seed = symbol.split('').reduce((acc, c) => acc + c.charCodeAt(0), 12345);
  function pseudoRandom() {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  }

  for (let i = count; i >= 0; i--) {
    const timestamp = now - i * interval;
    const date = new Date(timestamp);
    const timeStr = `${date.getHours().toString().padStart(2, '0')}:${date.getMinutes().toString().padStart(2, '0')}`;

    const deltaPercent = (pseudoRandom() - 0.485) * 0.012;
    const open = currentPrice;
    const close = Math.round((open * (1 + deltaPercent)) * 100) / 100;
    const spread = Math.abs(close - open) + open * 0.003 * pseudoRandom();
    const high = Math.round((Math.max(open, close) + spread * pseudoRandom()) * 100) / 100;
    const low = Math.round((Math.min(open, close) - spread * pseudoRandom()) * 100) / 100;
    const volume = Math.floor(15000 + pseudoRandom() * 60000);

    candles.push({
      timestamp,
      timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
    currentPrice = close;
  }
  return candles;
}

